(ns breto.proc
  "Programs breto runs. Everything but the interactive ones runs through
  briko.process: argv only, stdin closed, and output captured up to a bound.
  Those that finish on their own, such as cosign, hooks, tests and the token
  command, have a deadline after which the whole process tree is killed.
  Builds run through `run-in` without one, since how long a compiler takes
  depends on the package and the machine, and keep the end of their stderr,
  where a build prints its error. briko.process answers a program that cannot
  start with exit 127 and :launched? false; here that throws, as callers
  expect of a program that cannot run. Interactive programs run through
  `pick` with babashka.process, since they need the terminal."
  (:require [babashka.process :as process]
            [briko.process :as bprocess]
            [clojure.string :as str]))

(def command-timeout
  "Seconds a command run by `run-command` may take: cosign fetching its trust
  root over a slow network takes seconds, and a hung one would otherwise hold
  an install forever."
  600)

(def max-out-bytes
  "The stdout kept of a bounded command. A completion script or man page
  generated by a tool is far smaller; a command printing more is refused,
  since breto would otherwise install a cut-off file."
  (* 16 1024 1024))

(def max-build-err-bytes
  "The end of a build's stderr that is kept. A compiler's error and the lines
  leading to it fit; the progress a build printed before them is dropped."
  (* 1024 1024))

(defn- env-of [env]
  (into {} (map (fn [[k v]] [(str k) (str v)])) env))

(defn- run!
  "Runs `command` with briko.process and `opts`, throwing an IOException when
  it cannot start and an ex-info when it prints more than `max-out-bytes`."
  [command opts]
  (let [command (mapv str command)
        {:keys [launched? out-truncated?] :as result}
        (bprocess/run command (merge {:max-out-bytes max-out-bytes} opts))]
    (cond
      ;; An IOException, as babashka.process throws, so every caller that
      ;; tells a program that cannot start from one that fails still can.
      (not launched?)
      (throw (java.io.IOException. (str/trim (str (:err result)))))

      out-truncated?
      (throw (ex-info (str (first command) " printed more than " max-out-bytes " bytes")
                      {:breto/problem :output-too-large :program (first command)}))

      :else result)))

(defn run-command
  "Runs `command`, a sequence of program and arguments, returning its exit code
  and output. A program that cannot start, or runs longer than
  `command-timeout` seconds, throws."
  [command]
  (let [{:keys [timed-out?] :as result} (run! command {:timeout-ms (* 1000 command-timeout)})]
    (when timed-out?
      (throw (ex-info (str (first command) " ran longer than " command-timeout " seconds and was stopped")
                      {:breto/problem :timed-out :program (str (first command)) :timeout command-timeout})))
    (select-keys result [:exit :out :err])))

(defn run-bounded
  "Runs `command` with `env` added to the environment, in `dir` when given,
  and waits at most `timeout` seconds; a command still running then is
  stopped with every process it started. A program that cannot start throws."
  [{:keys [command env timeout dir]}]
  (let [result (run! command (cond-> {:timeout-ms (* 1000 timeout) :extra-env (env-of env)}
                               dir (assoc :dir (str dir))))]
    (if (:timed-out? result)
      {:exit nil :out "" :err "" :timed-out true}
      (select-keys result [:exit :out :err]))))

(defn pick
  "Runs the interactive `command` with `input` on its stdin and the terminal
  for everything else, returning its exit code and what it printed."
  [command input]
  (select-keys @(apply process/process {:in input :out :string :err :inherit} (map str command))
               [:exit :out]))

(defn ask
  "Prints `question` and reads one line of the answer, nil at the end of input."
  [question]
  (print question)
  (flush)
  (read-line))

(defn run-in
  "Runs `command` in `dir` with `env` added to the environment and the
  variables `unset` removed from it, returning its exit code and output. It
  runs until it finishes, with stdin closed; of its stderr the last
  `max-build-err-bytes` are kept. A program that cannot start throws, and so
  does one printing more than `max-out-bytes` on stdout."
  [{:keys [command env unset dir]}]
  (let [unset (set (map str unset))]
    (select-keys (run! command (cond-> {:timeout-ms :none
                                        :extra-env (env-of (remove (comp unset str key) env))
                                        :unset-env (vec unset)
                                        :max-err-bytes max-build-err-bytes
                                        :err-keep :tail}
                                 dir (assoc :dir (str dir))))
                 [:exit :out :err])))
